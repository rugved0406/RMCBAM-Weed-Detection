"""Generate the reports/ folder from the real dataset and code (re-runnable).

  python tools/build_reports.py --root "data/Himani mam images"

Outputs (reports/):
  dataset_inventory.json            folder counts, annotation inventory
  dataset_quality_all_images.csv    per-image resolution, padding, near-duplicate group, sharpness, green cover
  near_duplicate_groups.csv         images sharing an 8x8 average hash
  charts/*.png                      quality charts (resolution, padding, sharpness, green cover)
  recovered_boxes_preview/*.jpg     every recovered Weed/Crop box drawn on its source image
  recovered_boxes_contact_sheet.jpg overview of all previews
  patches_weed_contact_sheet.jpg    all Weed patches
  patches_crop_contact_sheet.jpg    all Crop/Flower patches
  architecture_cost.csv             YOLOv8s vs YOLOv8s+RMCBAM params / GFLOPs (built live)
  explainability_sanity/            Grad-CAM vs HiResCAM on Ultralytics' bus.jpg with a COCO model (needs yolov8s.pt)
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import cv2  # noqa: E402
import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from weedvision.config import PROJECT_ROOT, class_color_hex, hex_to_bgr  # noqa: E402
from weedvision.dataset import list_images, quality_table, scan_folder  # noqa: E402

SURF, INK, INK2, MUTED, GRID = "#1a1a19", "#f2f1ec", "#c3c2b7", "#898781", "#2c2c2a"
BLUE = "#3987e5"


def style(ax, title, xl, yl):
    ax.set_facecolor(SURF)
    ax.figure.set_facecolor(SURF)
    ax.set_title(title, color=INK, loc="left", fontsize=12)
    ax.set_xlabel(xl, color=MUTED)
    ax.set_ylabel(yl, color=MUTED)
    ax.tick_params(colors=INK2)
    for s in ax.spines.values():
        s.set_color("#383835")
    ax.grid(color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def hist(series, title, xl, path, bins=30):
    fig, ax = plt.subplots(figsize=(7, 3.6), dpi=130)
    ax.hist(series, bins=bins, color=BLUE, edgecolor=SURF, linewidth=1.5)
    style(ax, title, xl, "images")
    fig.tight_layout()
    fig.savefig(path, facecolor=SURF)
    plt.close(fig)


def contact_sheet(paths, out, tile=180, cols=10, labels=None, aspect=1.0):
    rows = (len(paths) + cols - 1) // cols
    th_ = int(tile * aspect)
    sheet = np.full((rows * (th_ + 20), cols * tile, 3), 26, np.uint8)
    for i, p in enumerate(paths):
        im = cv2.imread(str(p))
        if im is None:
            continue
        h, w = im.shape[:2]
        s = min((tile - 4) / w, (th_ - 2) / h)
        im = cv2.resize(im, (max(1, int(w * s)), max(1, int(h * s))), interpolation=cv2.INTER_AREA)
        r, c = divmod(i, cols)
        y0, x0 = r * (th_ + 20), c * tile
        sheet[y0 : y0 + im.shape[0], x0 : x0 + im.shape[1]] = im
        cv2.putText(sheet, (labels[i] if labels else Path(p).stem)[:24], (x0 + 3, y0 + im.shape[0] + 14), cv2.FONT_HERSHEY_SIMPLEX, 0.38, (195, 194, 183), 1, cv2.LINE_AA)
    cv2.imwrite(str(out), sheet, [cv2.IMWRITE_JPEG_QUALITY, 85])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="data/Himani mam images")
    ap.add_argument("--recovered", default="data/recovered/recovered_boxes.csv")
    ap.add_argument("--out", default="reports")
    a = ap.parse_args()
    root, out = Path(a.root), Path(a.out)
    (out / "charts").mkdir(parents=True, exist_ok=True)

    # ---------------- inventory
    sc = scan_folder(PROJECT_ROOT / "data")
    inv = {k: v for k, v in sc.items() if k not in ("images",)}
    inv["labelme_json"] = [str(Path(p).relative_to(PROJECT_ROOT)) for p in sc["labelme_json"]]
    inv["root"] = "data"
    inv["yaml_files"] = [str(Path(p).relative_to(PROJECT_ROOT)) for p in sc["yaml_files"]]
    inv["note"] = "LabelMe JSONs listed here were generated by tools/recover_patch_boxes.py; the original zip had none."
    (out / "dataset_inventory.json").write_text(json.dumps(inv, indent=2))
    print("inventory:", sc["n_images"], "images,", sc["n_labelme_json"], "LabelMe JSON")

    # ---------------- quality
    imgs = list_images(root)
    q = quality_table([str(p) for p in imgs])
    q["relpath"] = [str(Path(p).relative_to(root)) for p in q["path"]]
    q.drop(columns=["path"]).to_csv(out / "dataset_quality_all_images.csv", index=False)
    orig = q[q["folder"] == "Origanal"]
    dups = orig[orig["dup_count"] > 1].sort_values("dup_group")[["dup_group", "relpath", "width", "height", "black_border_frac"]]
    dups.to_csv(out / "near_duplicate_groups.csv", index=False)
    summary = {
        "originals": int(len(orig)),
        "originals_likely_augmented": int(orig["likely_augmented"].sum()),
        "originals_in_near_duplicate_groups": int((orig["dup_count"] > 1).sum()),
        "near_duplicate_groups": int((orig.groupby("dup_group").size() > 1).sum()),
        "distinct_resolutions": int(orig.groupby(["width", "height"]).ngroups),
        "top_resolutions": {f"{w}x{h}": int(n) for (w, h), n in orig.groupby(["width", "height"]).size().sort_values(ascending=False).head(5).items()},
        "median_sharpness_lapvar": float(orig["sharpness_lapvar"].median()),
        "median_green_frac": float(orig["green_frac"].median()),
    }
    (out / "dataset_quality_summary.json").write_text(json.dumps(summary, indent=2))
    print("quality:", summary)

    hist(orig["black_border_frac"] * 100, "Black padding per original image (rotation / warp augmentation)", "% of pixels black", out / "charts" / "padding.png")
    hist(orig["sharpness_lapvar"], "Sharpness (Laplacian variance) — originals", "variance (higher = sharper)", out / "charts" / "sharpness.png")
    hist(orig["green_frac"] * 100, "Vegetation cover proxy (% green pixels) — originals", "% green (HSV)", out / "charts" / "green.png")
    res = orig.groupby(["width", "height"]).size().reset_index(name="n")
    fig, ax = plt.subplots(figsize=(7, 3.6), dpi=130)
    ax.scatter(res["width"], res["height"], s=res["n"] * 6 + 20, color=BLUE, edgecolor=SURF, linewidth=1.5)
    for _, r in res.sort_values("n", ascending=False).head(4).iterrows():
        ax.annotate(f"{r.width}×{r.height}: {r.n}", (r.width, r.height), xytext=(6, 6), textcoords="offset points", color=INK2, fontsize=8)
    style(ax, "Original image resolutions (marker area ∝ count)", "width (px)", "height (px)")
    fig.tight_layout()
    fig.savefig(out / "charts" / "resolutions.png", facecolor=SURF)
    plt.close(fig)
    fig, ax = plt.subplots(figsize=(7, 3.6), dpi=130)
    cats = ["Augmented-looking", "Clean"]
    vals = [summary["originals_likely_augmented"], summary["originals"] - summary["originals_likely_augmented"]]
    ax.barh(cats, vals, color=[BLUE, "#898781"], edgecolor=SURF, linewidth=2, height=0.5)
    for i, v in enumerate(vals):
        ax.text(v + 4, i, f"{v} ({v / summary['originals']:.0%})", va="center", color=INK2)
    style(ax, "Originals with rotation/warp padding > 2%", "images", "")
    ax.set_xlim(0, max(vals) * 1.25)
    fig.tight_layout()
    fig.savefig(out / "charts" / "augmented.png", facecolor=SURF)
    plt.close(fig)

    # ---------------- patches + recovered boxes
    for kind, d in (("weed", root / "Crops" / "Weed_Crops"), ("crop", root / "Crops" / "Crop_Flower_Crops")):
        ps = list_images(d)
        if ps:
            contact_sheet(ps, out / f"patches_{kind}_contact_sheet.jpg", tile=150, cols=10)
    rec = Path(a.recovered)
    if rec.exists():
        df = pd.read_csv(rec)
        pv = out / "recovered_boxes_preview"
        pv.mkdir(exist_ok=True)
        previews = []
        for src, g in df[df["accepted"]].groupby("source"):
            p = PROJECT_ROOT / g.iloc[0]["source_path"] if not Path(g.iloc[0]["source_path"]).is_absolute() else Path(g.iloc[0]["source_path"])
            im = cv2.imread(str(p))
            if im is None:
                continue
            t = max(3, im.shape[1] // 300)
            for _, r in g.iterrows():
                col = hex_to_bgr(class_color_hex(r["label"]))
                cv2.rectangle(im, (int(r.x1), int(r.y1)), (int(r.x2), int(r.y2)), col, t)
                lab = f"{r['label']}  NCC {r['score']:.3f}"
                fs = im.shape[1] / 1400
                (tw, th), _ = cv2.getTextSize(lab, cv2.FONT_HERSHEY_SIMPLEX, fs, 2)
                y = max(int(r.y1), th + 8)
                cv2.rectangle(im, (int(r.x1), y - th - 8), (int(r.x1) + tw + 8, y), col, -1)
                cv2.putText(im, lab, (int(r.x1) + 4, y - 5), cv2.FONT_HERSHEY_SIMPLEX, fs, (20, 20, 20), 2, cv2.LINE_AA)
            s = 900 / im.shape[1]
            im = cv2.resize(im, (900, int(im.shape[0] * s)), interpolation=cv2.INTER_AREA)
            o = pv / f"{Path(src).stem}_recovered.jpg"
            cv2.imwrite(str(o), im, [cv2.IMWRITE_JPEG_QUALITY, 72])
            previews.append(o)
        contact_sheet(previews, out / "recovered_boxes_contact_sheet.jpg", tile=240, cols=7, labels=[p.stem.replace("_recovered", "") for p in previews], aspect=0.75)
        print("recovered previews:", len(previews))

    # ---------------- architecture cost
    from ultralytics.nn.tasks import DetectionModel

    from weedvision.models import model_gflops
    from weedvision.rmcbam import DEFAULT_RMCBAM_LAYERS, find_rmcbam, inject_rmcbam

    b = DetectionModel("yolov8s.yaml", nc=5, verbose=False)
    r_ = DetectionModel("yolov8s.yaml", nc=5, verbose=False)
    inject_rmcbam(r_)
    rows = []
    for name, m in (("YOLOv8s baseline", b), ("YOLOv8s + RMCBAM", r_)):
        rows.append({"model": name, "params": sum(p.numel() for p in m.parameters()), "GFLOPs@640": round(model_gflops(m) or 0, 3), "rmcbam_blocks": len(find_rmcbam(m)), "rmcbam_layers": str(list(DEFAULT_RMCBAM_LAYERS)) if find_rmcbam(m) else ""})
    per_block = [{"layer": n, "channels": a_.channels, "eca_kernel": a_.ca.k, "params": sum(p.numel() for p in a_.parameters())} for n, a_ in find_rmcbam(r_)]
    pd.DataFrame(rows).to_csv(out / "architecture_cost.csv", index=False)
    pd.DataFrame(per_block).to_csv(out / "rmcbam_blocks.csv", index=False)
    print(pd.DataFrame(rows).to_string(index=False))

    # ---------------- explainability sanity (COCO model on bus.jpg)
    w = PROJECT_ROOT / "yolov8s.pt"
    if w.exists():
        from ultralytics import YOLO
        from ultralytics.utils import ASSETS

        from weedvision.explain import DetectorCAM, energy_inside_box, overlay_heatmap
        from weedvision.inference import draw_detections, load_image_rgb, run_detection

        ed = out / "explainability_sanity"
        ed.mkdir(exist_ok=True)
        y = YOLO(str(w))
        img = load_image_rgb(str(ASSETS / "bus.jpg"))
        dets, _ = run_detection(y, img, 0.25, 0.45, 640, "cpu")
        people = [d for d in dets if d.cls_name == "person"][:3]
        cam = DetectorCAM(y.model, [15, 18, 21], "cpu")
        rows, tiles = [], []
        for meth in ("gradcam", "hirescam"):
            o = cam.explain(img, people, 640, method=meth)
            row_tiles = []
            for d in people:
                m = o["per_target"][d.uid]
                frac = d.area / (img.shape[0] * img.shape[1])
                e = energy_inside_box(m, d)
                rows.append({"method": meth, "detection": d.uid, "conf": round(d.conf, 3), "box_area_frac": round(frac, 4), "energy_in_box": round(e, 4), "ratio_vs_uniform": round(e / frac, 2)})
                t = overlay_heatmap(draw_detections(img, [d], show_conf=False), m, 0.5)
                t = cv2.resize(t, (300, 400))
                cv2.putText(t, f"{meth} {d.uid} x{e / frac:.1f}", (6, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2, cv2.LINE_AA)
                row_tiles.append(t)
            tiles.append(np.hstack(row_tiles))
        cv2.imwrite(str(ed / "gradcam_vs_hirescam_bus.jpg"), cv2.cvtColor(np.vstack(tiles), cv2.COLOR_RGB2BGR), [cv2.IMWRITE_JPEG_QUALITY, 88])
        pd.DataFrame(rows).to_csv(ed / "energy_in_box.csv", index=False)
        (ed / "README.txt").write_text(
            "COCO-pretrained yolov8s.pt on Ultralytics' sample bus.jpg, used only to validate the explanation code on a\n"
            "real, working detector. ratio_vs_uniform = share of heatmap mass inside the box / box share of the image\n"
            "(1.0 = no localisation). HiResCAM is the dashboard default because it localises far better than Grad-CAM.\n"
        )
        print(pd.DataFrame(rows).groupby("method")["ratio_vs_uniform"].mean())


if __name__ == "__main__":
    main()
